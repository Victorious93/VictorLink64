#ifndef VL64_GLPASS_SHADERS_H
#define VL64_GLPASS_SHADERS_H

#define VL_GLSL_VERSION "#version 300 es\n"

/* Full-screen triangle from gl_VertexID; vUv runs 0..1 across the window, +Y up. */
static const char *const VL_VS_BODY =
    "out vec2 vUv;\n"
    "void main() {\n"
    "  vec2 p = vec2(float((gl_VertexID << 1) & 2), float(gl_VertexID & 2));\n"
    "  vUv = p;\n"
    "  gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0);\n"
    "}\n";

/* Prefixed with "#define FX n". uSrc is the picture size in texels, uTexSize the texture size, uOut the window size. */
static const char *const VL_FS_BODY =
    "precision highp float;\n"
    "precision highp int;\n"
    "uniform sampler2D uTex;\n"
    "uniform vec2 uTexSize;\n"
    "uniform vec2 uSrc;\n"
    "uniform vec2 uOut;\n"
    "uniform float uFlip;\n"
    "in vec2 vUv;\n"
    "out vec4 oColor;\n"
    "\n"
    "vec3 smp(vec2 p) { return texture(uTex, clamp(p, vec2(0.5), uSrc - 0.5) / uTexSize).rgb; }\n"
    "vec3 texel(ivec2 i) { return texelFetch(uTex, clamp(i, ivec2(0), ivec2(uSrc) - 1), 0).rgb; }\n"
    "float luma(vec3 c) { return dot(c, vec3(0.299, 0.587, 0.114)); }\n"
    "bool same(vec3 a, vec3 b) { vec3 d = abs(a - b); return max(d.r, max(d.g, d.b)) < 0.06; }\n"
    "\n"
    "void main() {\n"
    "  vec2 p = vec2(vUv.x, mix(vUv.y, 1.0 - vUv.y, uFlip)) * uSrc;\n"
    "#if FX == 0\n"
    "  oColor = vec4(smp(p), 1.0);\n"
    "#elif FX == 1\n"
    "  vec3 c = smp(p);\n"
    "  vec3 n = smp(p + vec2(0.0, -1.0)), s = smp(p + vec2(0.0, 1.0)), e = smp(p + vec2(1.0, 0.0)), w = smp(p + vec2(-1.0, 0.0));\n"
    "  vec3 mn = min(c, min(min(n, s), min(e, w)));\n"
    "  vec3 mx = max(c, max(max(n, s), max(e, w)));\n"
    "  vec3 b = (n + s + e + w) * 0.25;\n"
    "  oColor = vec4(clamp(c + (c - b) * 0.8, mn, mx), 1.0);\n"
    "#elif FX == 2\n"
    "  vec2 px = uSrc / uOut;\n"
    "  vec3 rgbNW = smp(p + vec2(-1.0, -1.0) * px);\n"
    "  vec3 rgbNE = smp(p + vec2( 1.0, -1.0) * px);\n"
    "  vec3 rgbSW = smp(p + vec2(-1.0,  1.0) * px);\n"
    "  vec3 rgbSE = smp(p + vec2( 1.0,  1.0) * px);\n"
    "  vec3 rgbM = smp(p);\n"
    "  float lNW = luma(rgbNW), lNE = luma(rgbNE), lSW = luma(rgbSW), lSE = luma(rgbSE), lM = luma(rgbM);\n"
    "  float lMin = min(lM, min(min(lNW, lNE), min(lSW, lSE)));\n"
    "  float lMax = max(lM, max(max(lNW, lNE), max(lSW, lSE)));\n"
    "  vec2 dir = vec2(-((lNW + lNE) - (lSW + lSE)), (lNW + lSW) - (lNE + lSE));\n"
    "  float dirReduce = max((lNW + lNE + lSW + lSE) * 0.03125, 0.0078125);\n"
    "  float rcpDirMin = 1.0 / (min(abs(dir.x), abs(dir.y)) + dirReduce);\n"
    "  dir = clamp(dir * rcpDirMin, vec2(-8.0), vec2(8.0)) * px;\n"
    "  vec3 rgbA = 0.5 * (smp(p + dir * (1.0 / 3.0 - 0.5)) + smp(p + dir * (2.0 / 3.0 - 0.5)));\n"
    "  vec3 rgbB = rgbA * 0.5 + 0.25 * (smp(p + dir * -0.5) + smp(p + dir * 0.5));\n"
    "  float lB = luma(rgbB);\n"
    "  oColor = vec4((lB < lMin || lB > lMax) ? rgbA : rgbB, 1.0);\n"
    "#elif FX == 3\n"
    "  vec3 c = smp(p);\n"
    "  float ratio = uOut.y / uSrc.y;\n"
    "  float fade = clamp((ratio - 1.5) / 1.5, 0.0, 1.0);\n"
    "  float line = 0.5 + 0.5 * cos(6.2831853 * (p.y - 0.5));\n"
    "  float scan = mix(1.0, mix(0.68, 1.0, pow(line, 0.8)), fade);\n"
    "  float m = mod(floor(gl_FragCoord.x), 3.0);\n"
    "  vec3 mask = mix(vec3(1.0), vec3(m < 0.5 ? 1.0 : 0.82, (m > 0.5 && m < 1.5) ? 1.0 : 0.82, m > 1.5 ? 1.0 : 0.82), fade);\n"
    "  oColor = vec4(clamp(c * scan * mask * 1.12, 0.0, 1.0), 1.0);\n"
    "#else\n"
    "  vec2 ip = floor(p);\n"
    "  vec2 f = p - ip;\n"
    "  ivec2 i = ivec2(ip);\n"
    "  vec3 E = texel(i);\n"
    "  vec3 A = texel(i + ivec2(0, -1));\n"
    "  vec3 B = texel(i + ivec2(1, 0));\n"
    "  vec3 C = texel(i + ivec2(-1, 0));\n"
    "  vec3 D = texel(i + ivec2(0, 1));\n"
    "  vec3 P1 = (same(C, A) && !same(C, D) && !same(A, B)) ? A : E;\n"
    "  vec3 P2 = (same(A, B) && !same(A, C) && !same(B, D)) ? B : E;\n"
    "  vec3 P3 = (same(D, C) && !same(D, B) && !same(C, A)) ? C : E;\n"
    "  vec3 P4 = (same(B, D) && !same(B, A) && !same(D, C)) ? D : E;\n"
    "  vec2 sc = max(uOut / uSrc, vec2(1.0));\n"
    "  vec2 h = clamp(0.5 / sc, vec2(0.001), vec2(0.5));\n"
    "  vec2 w = smoothstep(vec2(0.5) - h, vec2(0.5) + h, f);\n"
    "  vec3 q = mix(mix(P1, P2, w.x), mix(P3, P4, w.x), w.y);\n"
    "  vec2 hi = smoothstep(vec2(1.0) - h, vec2(1.0), f);\n"
    "  vec2 lo = vec2(1.0) - smoothstep(vec2(0.0), h, f);\n"
    "  q = mix(q, B, 0.5 * hi.x);\n"
    "  q = mix(q, C, 0.5 * lo.x);\n"
    "  q = mix(q, D, 0.5 * hi.y);\n"
    "  q = mix(q, A, 0.5 * lo.y);\n"
    "  oColor = vec4(q, 1.0);\n"
    "#endif\n"
    "}\n";

#endif
